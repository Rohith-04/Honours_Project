#!/usr/bin/env python3
"""gen_soc_map.py — generate sw/common/soc_map.h from rtl/soc/soc_pkg.sv.

Single source of truth: soc_pkg.sv. Never hand-edit the generated header;
re-run this script instead:
    python3 scripts/gen_soc_map.py

Parses the localparam lines for bases/sizes/register offsets/widths and
emits C #defines. Fails loudly on any missing field so address drift
breaks the build instead of silently testing the wrong address.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "rtl" / "soc" / "soc_pkg.sv"
OUT = ROOT / "sw" / "common" / "soc_map.h"

FIELDS_32 = [
    "RAM_BASE", "RAM_BYTES",
    "UART_BASE",
    "TIMER_BASE",
    "GPIO_BASE",
    "UART_RBR", "UART_THR", "UART_IER", "UART_BAUD", "UART_LCR", "UART_LSR",
    "TIMER_CTRL", "TIMER_COUNT", "TIMER_COMPARE",
    "GPIO_OUT", "GPIO_IN", "GPIO_DIR",
]
FIELDS_INT = [
    "UART_LSR_DATA_READY", "UART_LSR_THRE", "UART_LSR_TEMT",
    "TIMER_CTRL_ENABLE", "TIMER_CTRL_MATCH",
    "GPIO_WIDTH",
]


def parse_pkg(text):
    vals = {}
    for name in FIELDS_32 + FIELDS_INT:
        # matches: localparam [logic [31:0] | int unsigned] NAME = <expr>;
        m = re.search(
            r"localparam\s+(?:logic\s*\[31:0\]\s*|int\s+unsigned\s*)"
            + re.escape(name) + r"\s*=\s*([^;]+);",
            text,
        )
        if not m:
            raise SystemExit(f"[gen_soc_map] missing {name} in {PKG}")
        expr = m.group(1).strip()
        # Normalize SystemVerilog literals to C: 32'h1000_0000 -> 0x10000000
        expr = expr.replace("_", "")
        expr = re.sub(r"\d+'h", "0x", expr)
        expr = re.sub(r"\d+'d", "", expr)
        expr = re.sub(r"\d+'b", "0b", expr)
        vals[name] = expr
    return vals


def main():
    text = PKG.read_text()
    vals = parse_pkg(text)
    lines = [
        "// GENERATED by scripts/gen_soc_map.py from rtl/soc/soc_pkg.sv.",
        "// Do not hand-edit. Re-run the generator instead.",
        "#ifndef SOC_MAP_H",
        "#define SOC_MAP_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for n in FIELDS_32:
        lines.append(f"#define SOC_{n} ((uint32_t)({vals[n]}))")
    for n in FIELDS_INT:
        lines.append(f"#define SOC_{n} ({vals[n]})")
    lines += [
        "",
        "// Absolute peripheral register addresses (base + offset).",
        "#define SOC_UART_RBR_ADDR    (SOC_UART_BASE + SOC_UART_RBR)",
        "#define SOC_UART_THR_ADDR    (SOC_UART_BASE + SOC_UART_THR)",
        "#define SOC_UART_IER_ADDR    (SOC_UART_BASE + SOC_UART_IER)",
        "#define SOC_UART_BAUD_ADDR   (SOC_UART_BASE + SOC_UART_BAUD)",
        "#define SOC_UART_LCR_ADDR    (SOC_UART_BASE + SOC_UART_LCR)",
        "#define SOC_UART_LSR_ADDR    (SOC_UART_BASE + SOC_UART_LSR)",
        "#define SOC_TIMER_CTRL_ADDR    (SOC_TIMER_BASE + SOC_TIMER_CTRL)",
        "#define SOC_TIMER_COUNT_ADDR   (SOC_TIMER_BASE + SOC_TIMER_COUNT)",
        "#define SOC_TIMER_COMPARE_ADDR (SOC_TIMER_BASE + SOC_TIMER_COMPARE)",
        "#define SOC_GPIO_OUT_ADDR (SOC_GPIO_BASE + SOC_GPIO_OUT)",
        "#define SOC_GPIO_IN_ADDR  (SOC_GPIO_BASE + SOC_GPIO_IN)",
        "#define SOC_GPIO_DIR_ADDR (SOC_GPIO_BASE + SOC_GPIO_DIR)",
        "",
        "// SW result signature word: dedicated .signature section at this",
        "// fixed RAM address (see sw/common/linker.ld). TB reads it via",
        "// hierarchical RAM access as an independent check next to UART.",
        "#define SOC_SW_RESULT_ADDR ((volatile uint32_t *)0x00007FF0UL)",
        "#define SOC_SW_RESULT_PASS 0x50515353UL // 'PASS'",
        "",
        "#endif // SOC_MAP_H",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"[gen_soc_map] wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
